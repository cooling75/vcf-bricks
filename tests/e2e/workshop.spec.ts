test.beforeEach(async ({page})=>{await page.goto('./');await page.evaluate(()=>localStorage.clear());await page.reload();});
test('build, configure, persist, export and reject unsafe imports',async({page})=>{
  await expect(page.getByRole('heading',{name:'Bausteine',exact:true})).toBeVisible();
  page.on('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Neuer Entwurf',exact:true}).click();
  await page.getByRole('button',{name:'vCenter Server hinzufügen',exact:true}).click();
  await page.getByLabel('Komponentenname',{exact:true}).fill('Workshop vCenter');
  await page.getByLabel('Version',{exact:true}).fill('9.0');
  await page.getByLabel('Notizen',{exact:true}).fill('<script>alert("not executable")</script>');
  await page.waitForTimeout(400);
  await page.reload();
  await page.getByRole('button',{name:'Struktur',exact:true}).click();
  await page.getByRole('button',{name:'Workshop vCenter auswählen',exact:true}).click();
  await expect(page.getByLabel('Version',{exact:true})).toHaveValue('9.0');
  await expect(page.getByLabel('Notizen',{exact:true})).toHaveValue('<script>alert("not executable")</script>');
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'JSON exportieren',exact:true}).click();
  const download=await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/\.json$/);
  const exportedPath = await download.path();
  expect(exportedPath).toBeTruthy();
  await page.getByRole('button',{name:'Neuer Entwurf',exact:true}).click();
  await page.locator('input[type=file]').setInputFiles(exportedPath!);
  await page.getByRole('button',{name:'Workshop vCenter auswählen',exact:true}).click();
  await expect(page.getByLabel('Version',{exact:true})).toHaveValue('9.0');
  await page.locator('input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schemaVersion":99}')});
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByLabel('Komponentenname',{exact:true})).toHaveValue('Workshop vCenter');
});
